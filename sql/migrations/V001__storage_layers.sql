-- V001. Слои хранения.
-- Каждый слой — отдельная схема. Ответственность слоя зафиксирована
-- в комментарии к схеме и видна прямо в базе: \dn+ в psql.

CREATE SCHEMA IF NOT EXISTS raw;
COMMENT ON SCHEMA raw IS
    'RAW: ответы источников без изменений (JSON, CSV) с отметкой загрузки. '
    'Только дописывание. Позволяет переобработать данные без повторного обращения к источнику.';

CREATE SCHEMA IF NOT EXISTS staging;
COMMENT ON SCHEMA staging IS
    'STAGING: очищенные и типизированные данные: единые единицы измерения, время в UTC, '
    'без дублей. Строки, не прошедшие проверки качества, отправляются в карантин.';

CREATE SCHEMA IF NOT EXISTS core;
COMMENT ON SCHEMA core IS
    'CORE: единая модель данных: справочники (станции, источники, даты, погодные явления), '
    'факты наблюдений и прогнозов, история изменений.';

CREATE SCHEMA IF NOT EXISTS mart;
COMMENT ON SCHEMA mart IS
    'MART: витрины под конкретные вопросы пользователя — источник данных для дашбордов и моделей.';

CREATE SCHEMA IF NOT EXISTS meta;
COMMENT ON SCHEMA meta IS
    'META: служебные метаданные: миграции схемы, журнал загрузок, отметки инкрементальной '
    'загрузки, результаты проверок качества.';
